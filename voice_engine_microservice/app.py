@app.post("/verify")
async def verify_voice(
    audio_file: UploadFile = File(...),
    authorization: str = Header(None)
):
    """
    Main endpoint. Accepts an audio file and returns who is speaking.
    Returns: { speaker: 'boss' | 'known:<name>' | 'unknown', confidence: float, liveness: bool }
    """
    # 1. Security Check
    if not authorization or authorization != f"Bearer {API_SECRET_KEY}":
        raise HTTPException(status_code=401, detail="Unauthorized: Invalid API Key")

    if verification_model is None:
        raise HTTPException(status_code=503, detail="Voice model is not loaded yet. Try again in a few seconds.")

    # 2. Read audio bytes
    audio_bytes = await audio_file.read()
    logger.info(f"Received audio for verification: {len(audio_bytes)} bytes")

    # 3. Anti-Spoofing / Liveness Check
    is_live = is_live_audio(audio_bytes)
    if not is_live:
        logger.warning("Liveness check FAILED — possible replay attack detected!")
        return JSONResponse({
            "speaker": "rejected",
            "confidence": 0.0,
            "liveness": False,
            "reason": "Anti-spoofing check failed. Live voice required."
        })

    # 4. Save audio to temp file for SpeechBrain
    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as tmp:
        tmp.write(audio_bytes)
        tmp_path = tmp.name

    try:
        import torch
        # 5. Extract embedding of the incoming audio
        waveform = verification_model.load_audio(tmp_path)
        batch = waveform.unsqueeze(0)
        with torch.no_grad():
            incoming_embedding = verification_model.encode_batch(batch)
        incoming_emb = incoming_embedding.squeeze().numpy()

        # 6. Compare against Boss Profile
        boss_emb = get_boss_embedding()
        if boss_emb is not None:
            boss_similarity = compute_similarity(incoming_emb, boss_emb)
            logger.info(f"Boss similarity score: {boss_similarity:.4f}")
            # Threshold: 0.75 is strict. Adjust if needed.
            if boss_similarity >= 0.75:
                return JSONResponse({
                    "speaker": "boss",
                    "confidence": round(boss_similarity, 4),
                    "liveness": True
                })

        # 7. Compare against known profiles (from Supabase — passed via request body in future)
        # For now, return unknown if not boss
        return JSONResponse({
            "speaker": "unknown",
            "confidence": 0.0,
            "liveness": True,
            # Include embedding so Node.js server can save it to Supabase for enrollment
            "embedding": base64.b64encode(incoming_emb.astype(np.float32).tobytes()).decode('utf-8')
        })

    finally:
        os.remove(tmp_path)


@app.post("/enroll")
async def enroll_speaker(
    audio_file: UploadFile = File(...),
    authorization: str = Header(None)
):
    """
    Generates and returns a voice embedding for a given audio file.
    Used by the enrollment script to generate the boss profile.
    """
    if not authorization or authorization != f"Bearer {API_SECRET_KEY}":
        raise HTTPException(status_code=401, detail="Unauthorized")

    if verification_model is None:
        raise HTTPException(status_code=503, detail="Model not loaded")

    audio_bytes = await audio_file.read()
    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as tmp:
        tmp.write(audio_bytes)
        tmp_path = tmp.name

    try:
        import torch
        waveform = verification_model.load_audio(tmp_path)
        batch = waveform.unsqueeze(0)
        with torch.no_grad():
            embedding = verification_model.encode_batch(batch)
        emb_np = embedding.squeeze().numpy().astype(np.float32)
        emb_b64 = base64.b64encode(emb_np.tobytes()).decode('utf-8')
        return JSONResponse({"embedding": emb_b64, "shape": list(emb_np.shape)})
    finally:
        os.remove(tmp_path)
