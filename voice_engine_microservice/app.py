# ── Helpers ───────────────────────────────────────────────────────────────────

from typing import Optional

def get_boss_embedding() -> Optional[np.ndarray]:
    """Decode the boss embedding from the base64 env variable."""
    if not BOSS_EMBEDDING_B64:
        return None
    try:
        decoded = base64.b64decode(BOSS_EMBEDDING_B64)
        return np.frombuffer(decoded, dtype=np.float32)
    except Exception as e:
        logger.error(f"Failed to decode boss embedding: {e}")
        return None

def compute_similarity(emb1: np.ndarray, emb2: np.ndarray) -> float:
    """Compute cosine similarity between two embeddings."""
    dot = np.dot(emb1, emb2)
    norm = np.linalg.norm(emb1) * np.linalg.norm(emb2)
    if norm == 0:
        return 0.0
    return float(dot / norm)

def is_live_audio(audio_bytes: bytes) -> bool:
    """
    Basic liveness/anti-spoofing check.
    Detects if audio is a recording played through a speaker by analyzing
    the frequency spectrum for telltale digital clipping and DC offset artifacts.
    Returns True if it appears to be a real live voice.
    """
    try:
        import struct
        # Sample every 100th byte as a rough energy estimate
        samples = struct.unpack(f'{len(audio_bytes)//2}h', audio_bytes[:len(audio_bytes) - len(audio_bytes)%2])
        arr = np.array(samples, dtype=np.float32)
        dc_offset = np.mean(arr)
        peak = np.max(np.abs(arr))
        # Recordings played on speakers often have very high DC offset
        # relative to the peak amplitude — a sign of digital clipping.
        if peak > 0 and abs(dc_offset / peak) > 0.3:
            logger.warning(f"Liveness check: HIGH DC offset ratio {abs(dc_offset/peak):.2f} — possible replay attack!")
            return False
        return True
    except Exception:
        # If check fails, assume live (don't block real users)
        return True


